"""Extract the contract's example scenario manifest into a C++ fixture header.

The manifest in notes/runtime-validation.md §Scenario manifest is the only worked example
of `mh-scenario/1`, so it is the positive fixture. Extracted mechanically for the same
reason as the trace fixture: a retyped fixture cannot be re-verified against the note.
"""

import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[2]
NOTE = REPO / "notes" / "runtime-validation.md"
OUT = REPO / "harness" / "tests" / "fixtures" / "example_scenario.hpp"

text = NOTE.read_text(encoding="utf-8")
marker = "## Scenario manifest"
start = text.index(marker)
block = re.search(r"```json\n(.*?)\n```", text[start:], re.S)
if block is None:
    raise SystemExit("no json block after the scenario-manifest heading")

body = block.group(1)
assert body.lstrip().startswith("{"), "the example should be one JSON object"
assert body.count("{") == body.count("}"), "unbalanced braces in the extracted manifest"

header = f'''// Generated by harness/tools/gen_example_scenario_fixture.py - do not edit by hand.
//
// The example `mh-scenario/1` manifest from notes/runtime-validation.md section
// "Scenario manifest", copied byte for byte. It is `status: draft`, so it validates but is
// not eligible for M3 evidence.

#pragma once

#include <string_view>

namespace mh_test_fixtures {{

inline constexpr std::string_view kExampleScenario =
    R"MHSCENARIO({body})MHSCENARIO";

}} // namespace mh_test_fixtures
'''

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(header, encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(body.splitlines())} lines, {len(body)} bytes)")
