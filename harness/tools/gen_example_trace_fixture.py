"""Extract the contract's seven-line example trace into a C++ fixture header.

The example in notes/runtime-validation.md section "Complete illustrative trace is declared valid
by the note, so it is the positive fixture for the reader and (item 11) the round-trip
target. Extracting it mechanically avoids a transcription error in a fixture nobody can
re-verify by eye.
"""

import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parents[2]
NOTE = REPO / "notes" / "runtime-validation.md"
OUT = REPO / "harness" / "tests" / "fixtures" / "example_trace.hpp"

text = NOTE.read_text(encoding="utf-8")
marker = "### Complete illustrative trace"
start = text.index(marker)
block = re.search(r"```jsonl\n(.*?)\n```", text[start:], re.S)
if block is None:
    raise SystemExit("no jsonl block after the illustrative-trace heading")

lines = block.group(1).splitlines()
assert len(lines) == 7, f"expected the seven-line example, found {len(lines)}"
assert all(line.startswith("{") and line.endswith("}") for line in lines)

header = f'''// Generated by harness/tools/gen_example_trace_fixture.py - do not edit by hand.
//
// The seven-line example trace from notes/runtime-validation.md section "Complete illustrative
// trace", copied byte for byte. The note declares it valid, so it is the reader's positive
// fixture and (item 11) the round-trip target. The embedded strings are a format example,
// not a captured run: the hashes are placeholders and no game data is present.

#pragma once

#include <string_view>

namespace mh_test_fixtures {{

inline constexpr std::string_view kExampleTrace =
    R"MHTRACE({chr(10).join(lines)})MHTRACE";

}} // namespace mh_test_fixtures
'''

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(header, encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(lines)} lines, {sum(len(line) + 1 for line in lines)} bytes)")
